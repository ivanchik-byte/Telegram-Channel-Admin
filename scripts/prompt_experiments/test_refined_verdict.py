import asyncio
from openai import AsyncOpenAI
from src.core.config import settings

async def main():
    client = AsyncOpenAI(
        base_url=settings.AI_BASE_URL,
        api_key=settings.AI_API_KEY
    )

    prompt = """Ты — автор живого технического Telegram-канала. Пиши сочно, живо, без тоски и канцелярщины, как увлеченный разработчик рассказывает в чате.

СТРУКТУРА ПОСТА:
<b>Заголовок: цепляющая суть новости</b>

Первый абзац — живая суть новости: что вышло, кто автор, сочные цифры и метрики (<code>название</code>, <b>цифры</b>).

Второй абзац — как это работает на практике простыми словами через действие («Скармливаешь... — модель сама...»).

Комментарий — СТРОГО 5-10 СЛОВ: твоя личная короткая оценка практика (кому зайдет, в чём нюанс). НЕ копируй концовку оригинала («сохрани себе» и т.п.) — пиши свою мысль. Без плашек («Админ:»).

ПРАВИЛА ОФОРМЛЕНИЯ (Telegram HTML):
- <b>жирный</b> — для заголовка и 1-2 главных цифр/акцентов в тексте.
- <code>моноширинный</code> — для названий инструментов, репозиториев, моделей и команд.
- Эмодзи — 0 штук (или 1 в конце).
- Текст должен звучать бодро: используй живые глаголы («выкатил», «скармливаешь», «собирает на лету»).

ПРИМЕР:
<b>AutoCut 2.0 — авто-нарезка длинных видео в вертикальные клипы</b>

Инженер Джон Доу выкатил <code>AutoCut 2.0</code> — проект мгновенно собрал <b>15 000 звёзд</b> на GitHub. Утилита решает главную боль: отсмотр часовых подкастов ради минутных роликов.

Скармливаешь ссылку на видео — алгоритм сам выцепляет хуки, режет паузы, кадрирует в 9:16 и накладывает субтитры. На выходе получаем пачку готовых шортсов.

Спасет кучу времени, но сложный звук придется допиливать."""

    raw_news = """🚨 ЭТО БЕЗУМИЕ

Китайский разработчик только что выпустил БЕСПЛАТный инструмент, способный автоматически создавать видео для TikTok, Reels и YouTube Shorts.

Он называется MoneyPrinterTurbo.

И уже набрал более 100 000 звёзд на GitHub.

Вот как это работает:
1. Вводишь тему или ключевое слово
2. ИИ генерирует сценарий, озвучку и субтитры
3. Ищет визуальный материал, монтирует видео и выдаёт готовый результат

Всё происходит в едином рабочем процессе.
Сохрани себе этот инструмент."""

    full_payload = f"{prompt}\n\nЧерновик новости:\n{raw_news}"

    res = await client.chat.completions.create(
        model=settings.AI_MODEL,
        messages=[{'role': 'user', 'content': full_payload}],
        extra_body={'temperature': 0.65, 'top_p': 0.9, 'max_tokens': 800},
        timeout=60.0
    )

    print("=== OUTPUT ===")
    print(res.choices[0].message.content)
    print("=== END ===")

asyncio.run(main())
