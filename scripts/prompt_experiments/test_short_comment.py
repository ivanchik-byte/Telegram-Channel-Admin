import asyncio
from openai import AsyncOpenAI
from src.core.config import settings

async def main():
    client = AsyncOpenAI(
        base_url=settings.AI_BASE_URL,
        api_key=settings.AI_API_KEY
    )

    prompt = """Ты — редактор Telegram-канала о технологиях и софте. Пиши коротко, сочно, живым человеческим языком.

СТРУКТУРА ПОСТА:
<b>Заголовок: емкая суть новости</b>

Первый абзац — 1-2 предложения: что вышло, кто разработчик, главные цифры (звёзды GitHub, метрики).

Второй абзац — как это работает и чем полезно (коротко и без воды).

Комментарий админа — строго 5-10 СЛОВ. Короткая живая реплика без плашек «Админ:» или «На мой взгляд:».

ПРАВИЛА ОФОРМЛЕНИЯ (Telegram HTML):
- <b>жирный</b> — только для заголовка.
- <code>моноширинный</code> — для названий инструментов, моделей и команд.
- Никаких эмодзи, никакого канцелярита и рекламных штампов.
- Выдавай ТОЛЬКО готовый текст поста.

ПРИМЕР:
<b>AutoCut 2.0 — авто-нарезка длинных видео в вертикальные клипы</b>

Инженер Джон Доу выкатил <code>AutoCut 2.0</code>, собравший 15 000 звёзд на GitHub. Утилита решает рутину контентщиков: отсмотр часовых подкастов ради минутных роликов.

Скармливаешь ссылку на видео — алгоритм находит интересные моменты, убирает паузы, кадрирует в 9:16 и накладывает субтитры. На выходе — пачка готовых шортсов.

Спасет часы на нарезках, хотя сложный звук правится руками."""

    raw_news = """🚨 ЭТО БЕЗУМИЕ

Китайский разработчик только что выпустил БЕСПЛАТный инструмент, способный автоматически создавать видео для TikTok, Reels и YouTube Shorts.

Он называется MoneyPrinterTurbo.

И уже набрал более 100 000 звёзд на GitHub.

Вот как это работает:
1. Вводишь тему или ключевое слово
2. ИИ генерирует сценарий, озвучку и субтитры
3. Ищет визуальный материал, монтирует видео и выдаёт готовый результат

Всё происходит в едином рабочем процессе.
Сохрани себе этот инструмент."""

    full_payload = f"{prompt}\n\nЧерновик новости:\n{raw_news}"

    res = await client.chat.completions.create(
        model=settings.AI_MODEL,
        messages=[{'role': 'user', 'content': full_payload}],
        extra_body={'temperature': 0.6, 'top_p': 0.9, 'max_tokens': 800},
        timeout=60.0
    )

    print("=== OUTPUT ===")
    print(res.choices[0].message.content)
    print("=== END ===")

asyncio.run(main())
