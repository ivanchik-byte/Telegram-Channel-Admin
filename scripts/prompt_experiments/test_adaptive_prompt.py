import asyncio
from openai import AsyncOpenAI
from src.core.config import settings

async def main():
    client = AsyncOpenAI(
        base_url=settings.AI_BASE_URL,
        api_key=settings.AI_API_KEY
    )

    prompt = """Ты — автор и редактор Telegram-канала про технологии, софт и нейросети. Пиши живым, бодрым языком практикующего гика: без канцелярита, занудства и рекламного мусора.

ГЛАВНЫЕ ПРАВИЛА:
1. Факты неприкосновенны: используй ТОЛЬКО данные из входного текста. Запрещено выдумывать цифры или функции, которых нет в источнике.
2. Адаптивная структура:
   - Если это подборка / список из нескольких пунктов: сделай жирный заголовок, короткое вводное предложение, список пунктов через тире (название в <code>коде</code> + суть в 1 строку) и авторский вывод.
   - Если это новость про один инструмент / релиз: сделай жирный заголовок, 1-й абзац (суть новости, автор, цифры), 2-й абзац (как устроено и в чём польза) и авторский вывод.
3. Комментарий автора в конце — строго 10-20 слов: простая, связная мысль от первого лица (кому пригодится, в чём нюанс). НЕ копируй призывы и концовки из оригинала («сохрани себе», «подпишись»). Пиши мысль сразу, без плашек («Админ:», «Вердикт:»).
4. Оформление: Telegram HTML (<b>жирный</b> для заголовка и 1-2 ключевых цифр, <code>код</code> для названий инструментов, сервисов и команд). Без эмодзи в заголовке, 0-1 в тексте.

ПРИМЕР 1 (ПОДБОРКА / СПИСОК):
<b>5 открытых инструментов для ускорения фронтенда</b>

Собрали годные утилиты, которые решают частые боли веб-разработки:

— <code>Bundlephobia</code> — быстрый анализ веса npm-пакетов перед установкой;
— <code>Unplugin-Icons</code> — подключение любых иконок по требованию без раздувания бандла;
— <code>Playwright MCP</code> — запуск тестов интерфейса через ИИ-агентов.

Годная подборка в закладки: экономит часы рутины на настройке проектов и оптимизации скорости.

ПРИМЕР 2 (ОДИНОЧНЫЙ РЕЛИЗ):
<b>AutoCut 2.0 — авто-нарезка длинных видео в вертикальные клипы</b>

Инженер Джон Доу выкатил <code>AutoCut 2.0</code> — проект мгновенно собрал <b>15 000 звёзд</b> на GitHub. Утилита решает вечную рутину контентщиков: отсмотр часовых подкастов ради минутных роликов для соцсетей.

Скармливаешь ссылку на видео — алгоритм сам находит ключевые хуки, вырезает паузы, кадрирует в 9:16 и накладывает анимированные субтитры. На выходе получаем пачку готовых шортсов под ключ.

Штука отлично спасет время при регулярной нарезке простых роликов, но сложный звук всё равно придется допиливать руками."""

    raw_news = """🚨 ЭТО БЕЗУМИЕ

Китайский разработчик только что выпустил БЕСПЛАТный инструмент, способный автоматически создавать видео для TikTok, Reels и YouTube Shorts.

Он называется MoneyPrinterTurbo.

И уже набрал более 100 000 звёзд на GitHub.

Вот как это работает:
1. Вводишь тему или ключевое слово
2. ИИ генерирует сценарий, озвучку и субтитры
3. Ищет визуальный материал, монтирует видео и выдаёт готовый результат

Всё происходит в едином рабочем процессе.
Сохрани себе этот инструмент."""

    full_payload = f"{prompt}\n\nИсходный текст:\n{raw_news}"

    res = await client.chat.completions.create(
        model=settings.AI_MODEL,
        messages=[{'role': 'user', 'content': full_payload}],
        extra_body={'temperature': 0.6, 'top_p': 0.9, 'max_tokens': 800},
        timeout=60.0
    )

    print("=== RESULT FOR SINGLE ===")
    print(res.choices[0].message.content)
    print("=== END ===")

asyncio.run(main())
