import asyncio
from openai import AsyncOpenAI
from src.core.config import settings

async def main():
    client = AsyncOpenAI(
        base_url=settings.AI_BASE_URL,
        api_key=settings.AI_API_KEY
    )

    prompt = """Ты — автор техно-канала в Telegram. Пиши живо, ёмко и легко, как увлеченный гик рассказывает друзьям.

ФОРМАТ:
<b>Заголовок с сутью новости</b>

Первый абзац (1-2 предложения): что вышло, кто автор, сочные цифры (<b>100k звёзд</b>) и <code>названия</code> в моноширинном шрифте.

Второй абзац (1-2 предложения): как это работает простыми словами и в чём польза.

Комментарий (5-10 слов): твоя личная мысль-оценка практика. Никогда не копируй призывы и концовку из исходника («сохрани себе», «подпишись» и т.п.).

HTML-разметка: <b>жирный</b>, <code>код</code>. Без занудства, штампов и канцелярита.

ПРИМЕР:
<b>AutoCut 2.0 — авто-нарезка подкастов на клипы</b>

Инженер выкатил <code>AutoCut 2.0</code>, и он уже собрал <b>15 000 звёзд</b> на GitHub. Утилита спасает от нудного отсмотра часовых видео ради минутных шортсов.

Скармливаешь ролик — сетка сама вырезает паузы, находит огненные моменты, кадрирует в 9:16 и клеит субтитры.

Сэкономит кучу времени, но звук лучше перепроверить."""

    raw_news = """🚨 ЭТО БЕЗУМИЕ

Китайский разработчик только что выпустил БЕСПЛАТный инструмент, способный автоматически создавать видео для TikTok, Reels и YouTube Shorts.

Он называется MoneyPrinterTurbo.

И уже набрал более 100 000 звёзд на GitHub.

Вот как это работает:
1. Вводишь тему или ключевое слово
2. ИИ генерирует сценарий, озвучку и субтитры
3. Ищет визуальный материал, монтирует видео и выдаёт готовый результат

Всё происходит в едином рабочем процессе.
Сохрани себе этот инструмент."""

    full_payload = f"{prompt}\n\nЧерновик новости:\n{raw_news}"

    res = await client.chat.completions.create(
        model=settings.AI_MODEL,
        messages=[{'role': 'user', 'content': full_payload}],
        extra_body={'temperature': 0.7, 'top_p': 0.9, 'max_tokens': 600},
        timeout=60.0
    )

    print("=== OUTPUT ===")
    print(res.choices[0].message.content)
    print("=== END ===")

asyncio.run(main())
